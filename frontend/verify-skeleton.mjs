import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
let release;
const gate=new Promise(r=>release=r);
await page.route('**/api/metadata',async route=>{await gate; await route.continue();});
await page.goto('http://localhost:5173');
await page.getByRole('status',{name:'Loading Elexon data'}).waitFor();
if(await page.locator('.dashboard-skeleton .stat').count()!==3) throw Error('Decision skeleton missing');
await page.screenshot({path:'../.impeccable/review/skeleton-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Overflow');
await page.screenshot({path:'../.impeccable/review/skeleton-mobile.png',fullPage:true});
release();
await page.getByRole('heading',{name:'Delivery-day forecast',exact:true}).waitFor();
let releaseAccuracy;
const accuracyGate=new Promise(r=>releaseAccuracy=r);
await page.route('**/api/accuracy?**',async route=>{await accuracyGate; await route.continue();});
await page.getByRole('button',{name:'Accuracy',exact:true}).click();
await page.locator('.dashboard-skeleton .accuracy-stats').waitFor();
if(await page.locator('.dashboard-skeleton .stat').count()!==4) throw Error('Accuracy skeleton missing');
releaseAccuracy();
await page.getByRole('heading',{name:'Forecast meets actual',exact:true}).waitFor();
await browser.close();
console.log('PASS: delayed initial and accuracy loading, replacement with content, mobile overflow, reduced motion.');
